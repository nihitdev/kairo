ROOT = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config'))
PALETTES = {
    'arch-blue': dict(base='#0b1420', surface='#15283d', text='#c5e4ff', blue='#1793d1', cyan='#67d4ff', mauve='#62aaff', green='#7dcfff', red='#ff6b81', yellow='#9bdcff', peach='#56b6f0', overlay='#6889a8', arch='#1793d1'),
    'catppuccin': dict(base='#1e1e2e', surface='#313244', text='#cdd6f4', blue='#89b4fa', cyan='#94e2d5', mauve='#cba6f7', green='#a6e3a1', red='#f38ba8', yellow='#f9e2af', peach='#fab387', overlay='#6c7086', arch='#89b4fa'),
    'rose-pine': dict(base='#191724', surface='#26233a', text='#e0def4', blue='#31748f', cyan='#9ccfd8', mauve='#c4a7e7', green='#9ccfd8', red='#eb6f92', yellow='#f6c177', peach='#ebbcba', overlay='#908caa', arch='#9ccfd8'),
}

def write_atomic(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as f:
        f.write(content)
        temp = Path(f.name)
    temp.chmod(path.stat().st_mode & 0o777 if path.exists() else 0o644)
    temp.replace(path)

def reload_kitty():
    """Reload only this user's Kitty processes, without remote-control access."""
    count = 0
    if not Path('/proc').is_dir():
        return count
    for proc in Path('/proc').iterdir():
        if not proc.name.isdigit():
            continue
        try:
            if proc.stat().st_uid != os.getuid():
                continue
            if (proc/'exe').resolve().name != 'kitty':
                continue
            os.kill(int(proc.name), signal.SIGUSR1)
            count += 1
        except (OSError, ValueError):
            continue
    return count


def switch(name, reload=True):
    c = dict(PALETTES[name])
    c['accent'] = c['blue'] if name == 'arch-blue' else (c['peach'] if name == 'rose-pine' else c['mauve'])
    c['arch'] = c['accent']
    colors = dict(c, purple=c['mauve'], **{'bright-black':c['overlay']})
    palette = '\n[palettes.prism]\n' + ''.join(f'{k} = "{v}"\n' for k,v in colors.items())
    changes = {}
    for path in (ROOT/'starship').glob('*.toml'):
        s = re.sub(r'\n\[palettes\.(?:kairo|prism)\]\n.*?(?=\n\[|\Z)', '', path.read_text(), flags=re.S).rstrip()
        s = s.replace('palette = "kairo"', 'palette = "prism"')
        if not re.search(r'^palette\s*=', s, re.M):
            s = 'palette = "prism"\n' + s
        s = s.replace('bold cyan', 'bold accent')
        s += '\n' + palette
        tomllib.loads(s)
        changes[path] = s
    path = ROOT/'fastfetch/config.jsonc'
    cfg = json.loads(path.read_text())
    cfg['logo']['color'] = {'1':c['accent'], '2':c['cyan']}
    cfg['display']['color'] = {'keys':c['accent'], 'title':c['accent'], 'output':c['text'], 'separator':c['overlay']}
    for module in cfg['modules']:
        if isinstance(module,dict):
            module.pop('keyColor',None)
            if module['type'] in ('host', 'cpu', 'gpu', 'memory'):
                module['keyColor'] = c['mauve']
            elif module['type'] == 'uptime':
                module['keyColor'] = c['green']
            if module['type']=='title':
                module['color'] = {'user':c['cyan'], 'at':c['overlay'], 'host':c['accent']}
    changes[path] = json.dumps(cfg,ensure_ascii=False,indent=4)+'\n'
    # Keep picker behavior; shells replace only its --color options.
    fzf = '--color='+','.join(f'{key}:{c[role]}' for key,role in [('bg','base'),('bg+','surface'),('fg','text'),('fg+','text'),('hl','cyan'),('hl+','cyan'),('border','accent'),('prompt','accent'),('pointer','cyan'),('marker','green'),('spinner','cyan'),('header','blue')])
    fish = ['# Generated by prism theme switch; edit palettes in prism/prism.py.', 'status is-interactive; or return']
    roles = dict(normal='text',command='accent',keyword='mauve',quote='green',redirection='cyan',end='peach',error='red',param='text',comment='overlay',operator='cyan',escape='yellow',autosuggestion='overlay',cancel='red')
    for k,v in roles.items():fish.append(f'set -g fish_color_{k} {c[v][1:]}')
    for k in ['selection','search_match']:fish.append(f'set -g fish_color_{k} {c["text"][1:]} --background={c["surface"][1:]}')
    for k,v in dict(progress='overlay',prefix='blue',completion='text',description='overlay').items():fish.append(f'set -g fish_pager_color_{k} {c[v][1:]}')
    fish.append(f'set -g fish_pager_color_selected_background --background={c["surface"][1:]}')
    fish += ['set -l prism_fzf (string replace -ar -- "--color=[^ ]+" "" "$FZF_DEFAULT_OPTS")', f'set -gx FZF_DEFAULT_OPTS "$prism_fzf {fzf}"']
    changes[ROOT/'fish/conf.d/15-prism-theme.fish'] = '\n'.join(fish)+'\n'
    nu = dict(separator=c['overlay'],header=c['blue'],row_index=c['blue'],hints=c['overlay'],string=c['text'],int=c['cyan'],float=c['cyan'],bool=c['cyan'],shape_external=c['accent'],shape_external_resolved=c['accent'],shape_internalcall=c['accent'],shape_keyword=c['mauve'],shape_string=c['green'],shape_raw_string=c['green'],shape_flag=c['cyan'],shape_operator=c['cyan'],shape_pipe=c['cyan'],shape_variable=c['mauve'],shape_externalarg=c['text'],shape_garbage=c['red'])
    changes[ROOT/'prism/nu-colors.json'] = json.dumps(nu,indent=2)+'\n'
    changes[ROOT/'prism/fzf.txt'] = fzf+'\n'
    ansi = ['base','red','green','yellow','blue','mauve','cyan','text','overlay','red','green','yellow','blue','mauve','cyan','text']
    kitty = dict(background=c['base'],foreground=c['text'],cursor=c['cyan'],cursor_text_color=c['base'],selection_background=c['surface'],selection_foreground=c['text'],active_border_color=c['blue'],inactive_border_color=c['surface'],url_color=c['cyan'])
    kitty.update({f'color{i}':c[role] for i,role in enumerate(ansi)})
    changes[ROOT/'kitty/current-theme.conf'] = '# Generated by prism\n'+''.join(f'{k} {v}\n' for k,v in kitty.items())
    shell = 'export FZF_DEFAULT_OPTS="$(printf \'%s\' "${FZF_DEFAULT_OPTS:-}" | sed -E \'s/--color=[^ ]+//g\') '+fzf+'"\n'
    shell += 'if [ -n "${ZSH_VERSION:-}" ]; then\n  typeset -gA ZSH_HIGHLIGHT_STYLES\n'
    for key,role in [('command','accent'),('builtin','accent'),('alias','accent'),('reserved-word','mauve'),('single-quoted-argument','green'),('double-quoted-argument','green'),('comment','overlay'),('unknown-token','red')]:
        shell += f"  ZSH_HIGHLIGHT_STYLES[{key}]='fg={c[role]}'\n"
    shell += 'fi\n'
    changes[ROOT/'prism/theme.sh'] = shell
    current = current_theme()
    if current in PALETTES and current != name:
        changes[ROOT/'prism/previous'] = current+'\n'
    changes[ROOT/'prism/current'] = name+'\n'
    # Validate Fastfetch before touching active files.
    if shutil.which('fastfetch'):
      with tempfile.NamedTemporaryFile(mode='w',suffix='.jsonc') as f:
          f.write(changes[path]);f.flush()
          check = subprocess.run(['fastfetch','--config',f.name,'--pipe','true'],capture_output=True,text=True)
          if check.returncode or check.stderr:
              raise RuntimeError(check.stderr or check.stdout)
    backup = ROOT/'config-backups'/('prism-switch-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
    for p in changes:
        if p.exists():
            dest=backup/p.relative_to(ROOT);dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,dest)
    written = []
    try:
        for target, content in changes.items():
            write_atomic(target, content)
            written.append(target)
    except BaseException:
        for target in reversed(written):
            saved = backup / target.relative_to(ROOT)
            if saved.exists():
                write_atomic(target, saved.read_text())
            else:
                target.unlink(missing_ok=True)
        raise
    reloaded = reload_kitty() if reload else 0
    print(f'Theme: {name}. Prompt and Fastfetch updated; reloaded {reloaded} Kitty instance(s).')
    if not reload:
        print('Kitty reload skipped.')
    elif not reloaded:
        print('No running Kitty found. Other terminal apps may need their own reload.')
    print(f'Backup: {backup}')

def current_theme():
    path = ROOT/'prism/current'
    return path.read_text().strip() if path.exists() else 'unset'

def preview(name):
    print(f'{name} — preview only')
    colors = PALETTES[name]
    if os.isatty(1):
        for role in ['base', 'surface', 'blue', 'cyan', 'mauve', 'peach', 'green', 'red', 'text']:
            h = colors[role].lstrip('#')
            rgb = ';'.join(str(int(h[i:i+2], 16)) for i in (0,2,4))
            print(f'\033[48;2;{rgb}m    \033[0m {role:8} {colors[role]}')
    else:
        for role, value in colors.items():
            print(f'{role:8} {value}')

def main():
    parser=argparse.ArgumentParser(description='Prism — shared terminal themes, with live Kitty reload.')
    parser.add_argument('--no-reload', action='store_true', help='write colors without signaling running Kitty processes')
    sub=parser.add_subparsers(dest='command')
    theme=sub.add_parser('theme').add_subparsers(dest='action',required=True)
    theme.add_parser('list');theme.add_parser('current');theme.add_parser('back')
    theme.add_parser('switch').add_argument('name',choices=PALETTES)
    theme.add_parser('preview').add_argument('name',choices=PALETTES)
    args=parser.parse_args()
    if args.command is None:
        print(f'Prism · {current_theme()}\nUse: prism theme list | switch NAME | preview NAME | back')
    elif args.action=='list':
        for name in PALETTES:
            print(f'{"*" if name == current_theme() else " "} {name}')
    elif args.action=='current':print(current_theme())
    elif args.action=='preview':preview(args.name)
    elif args.action=='back':
        previous=ROOT/'prism/previous'
        name=previous.read_text().strip() if previous.exists() else ''
        if name not in PALETTES:
            parser.error('No previous theme yet. Switch to another theme first.')
        switch(name, reload=not args.no_reload)
    else:switch(args.name, reload=not args.no_reload)

if __name__=='__main__':main()
